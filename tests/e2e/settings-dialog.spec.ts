import AxeBuilder from "@axe-core/playwright";

import { expect, test } from "./fixtures";

test("设置弹框保留背景、保护表单并支持路由历史", async ({ page }, testInfo) => {
  test.setTimeout(90_000);
  await page.goto("/login");
  await page.getByLabel("邮箱").fill("admin@example.com");
  await page.getByLabel("密码").fill("AdminPass123!");
  await page.getByRole("button", { name: "登录" }).click();
  await expect(page).toHaveURL(/\/dashboard$/);
  await page.goto("/dashboard/projects?status=active");
  await page.getByRole("button", { name: "打开账户菜单" }).click();
  await page.getByRole("menuitem", { name: "设置", exact: true }).click();
  const dialog = page.getByRole("dialog", { name: "设置", exact: true });
  await expect(dialog).toBeVisible();
  await dialog.getByLabel("姓名").fill("尚未保存");
  await dialog.getByRole("button", { name: "关闭设置" }).click();
  await expect(page.getByRole("alertdialog")).toBeVisible();
  await page.getByRole("button", { name: "继续编辑" }).click();
  await expect(dialog.getByLabel("姓名")).toHaveValue("尚未保存");
  await dialog.getByRole("link", { name: "外观", exact: true }).click();
  await page.getByRole("button", { name: "放弃修改" }).click();
  await expect(dialog.getByRole("heading", { name: "外观", exact: true })).toBeVisible();
  await dialog.getByRole("button", { name: "深色", exact: true }).click();
  await expect(page.locator("html")).toHaveClass(/dark/);
  await dialog.getByRole("button", { name: "浅色", exact: true }).click();
  const bounds = await dialog.boundingBox();
  expect(bounds?.width).toBeLessThanOrEqual(880);
  expect((await new AxeBuilder({ page }).include('[role="dialog"]').analyze()).violations).toEqual([]);
  await page.screenshot({ path: testInfo.outputPath("settings-desktop.png") });
  await dialog.getByRole("link", { name: "安全", exact: true }).click();
  await expect(dialog.getByRole("heading", { name: "安全", exact: true })).toBeVisible();
  await expect(dialog.getByText("当前会话", { exact: true })).toBeVisible();
  await dialog.getByRole("link", { name: "关于", exact: true }).click();
  await expect(dialog.getByRole("heading", { name: "关于", exact: true })).toBeVisible();
  await page.keyboard.press("Escape");
  await expect(dialog).toBeHidden();
  await expect(page).toHaveURL(/\/dashboard\/projects\?status=active$/);
  await page.goForward();
  await expect(dialog).toBeVisible();
  await page.goBack();
  await expect(dialog).toBeHidden();
  await page.goForward();
  await expect(dialog).toBeVisible();
  await page.reload();
  await expect(dialog).toHaveCount(0);
  await expect(page.getByRole("heading", { name: "关于", exact: true })).toBeVisible();
  await page.goto("/dashboard/settings/appearance");
  await expect(dialog).toHaveCount(0);
  await expect(page.getByRole("heading", { name: "外观", exact: true })).toBeVisible();
});
